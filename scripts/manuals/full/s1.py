OPEN_PERSON = [("click", "link:เส้นทางหลัก"), ("wait", 800)]


def PERSON(name, key):
    """เปิดหน้าประวัติของบุคคลที่ระบุชื่อ แล้วไปแท็บที่ต้องการ"""
    return [("click", f"link:{name}"), ("wait", 800), ("click", f"css:a[href*=\"tab={key}\"]"), ("wait", 900)]


def TAB(key):
    return OPEN_PERSON + [("click", f"css:a[href*=\"tab={key}\"]"), ("wait", 900)]


