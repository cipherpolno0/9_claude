# แถบบนของเว็บติดอยู่ด้านบน (sticky) ถ้าไม่ปลดก่อน เมื่อเลื่อนไปเน้นจุดล่าง ๆ แถบจะทับภาพ
_STATIC_HEADER = ("eval", "document.querySelectorAll('header').forEach(h => { h.style.position = 'static'; })")


def SHOT(who, path, caption, pre=None, **kw):
    if kw.get("el") or kw.get("full"):
        pre = [_STATIC_HEADER] + list(pre or [])
    return _SHOT(who, path, caption, pre=pre, **kw)


