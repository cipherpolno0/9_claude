import ExcelJS from "exceljs";

import { requireMenu } from "@/lib/auth/guards";
import { workbookResponse } from "@/lib/excel";
import { PERSON_IMPORT_HEADERS } from "@/lib/persons";

/** แม่แบบ Excel สำหรับนำเข้าบุคคล */
export async function GET() {
  await requireMenu("/app/personnel");
  const workbook = new ExcelJS.Workbook();
  const sheet = workbook.addWorksheet("บุคคล");
  const widths = [12, 22, 20, 18, 20, 14, 20, 14, 10, 10, 18, 24, 24, 16, 16];
  sheet.columns = PERSON_IMPORT_HEADERS.map((header, i) => ({ header, width: widths[i] }));
  sheet.getRow(1).font = { bold: true };
  sheet.views = [{ state: "frozen", ySplit: 1 }];
  // วันที่ เลขประจำตัวประชาชน รหัสเขต และเบอร์ติดต่อ เก็บเป็นข้อความ เพื่อไม่ให้ Excel แปลงค่าเอง
  for (const col of [6, 7, 8, 10, 13, 14]) sheet.getColumn(col).numFmt = "@";

  const lists: Record<number, string> = {
    1: '"บรรพชิต,คฤหัสถ์"',
    9: '"ตรี,โท,เอก"',
    10: '"1-2,3,4,5,6,7,8,9"',
    15: '"ปฏิบัติหน้าที่,ย้ายแล้ว,ลาออก,มรณภาพ,ตาย,ลาสิกขา,พ้นตำแหน่งด้วยเหตุอื่น"',
  };
  for (let r = 2; r <= 2001; r++) {
    for (const [col, formula] of Object.entries(lists)) {
      sheet.getCell(r, Number(col)).dataValidation = { type: "list", allowBlank: true, formulae: [formula] };
    }
  }

  const help = workbook.addWorksheet("วิธีกรอก");
  help.columns = [{ width: 26 }, { width: 100 }];
  help.addRows([
    ["คอลัมน์", "คำอธิบาย"],
    ["ประเภท", "ต้องกรอก เลือกจากรายการ: บรรพชิต คฤหัสถ์"],
    ["คำนำหน้าหรือสมณศักดิ์", "เช่น พระ พระมหา พระครู... นาย นาง"],
    ["ชื่อ", "ต้องกรอก"],
    ["ฉายา", "เฉพาะบรรพชิต"],
    ["นามสกุล", ""],
    ["วันเกิด", "รูปแบบ วว/ดด/ปปปป เป็นปี พ.ศ. เช่น 15/04/2520"],
    ["เลขประจำตัวประชาชน", "ตัวเลข 13 หลัก เว้นว่างได้ ระบบเก็บแบบเข้ารหัสและแสดงเฉพาะ 4 ตัวท้าย"],
    ["วันอุปสมบท", "เฉพาะบรรพชิต รูปแบบ วว/ดด/ปปปป เป็นปี พ.ศ. ระบบใช้คำนวณพรรษา"],
    ["น.ธ.", "เลือกจากรายการ: ตรี โท เอก (เว้นว่างได้)"],
    ["ป.ธ.", "เลือกจากรายการ: 1-2 หรือ 3 ถึง 9 (เว้นว่างได้)"],
    ["วุฒิสามัญ", "เช่น ม.6 ปริญญาตรี"],
    ["วัดที่สังกัด", "ชื่อวัด"],
    ["รหัสเขตปกครอง", "ต้องกรอก รหัสของตำบล (หรืออำเภอ จังหวัด ภาค) ที่วัดตั้งอยู่ ต้องเป็นเขตที่ท่านบันทึกได้"],
    ["เบอร์ติดต่อ", ""],
    ["สถานะ", "เลือกจากรายการ: ปฏิบัติหน้าที่ ย้ายแล้ว ลาออก มรณภาพ ตาย ลาสิกขา พ้นตำแหน่งด้วยเหตุอื่น (เว้นว่าง = ปฏิบัติหน้าที่)"],
    ["", ""],
    ["ข้อควรทราบ", "กรอกข้อมูลในแผ่นงานแรก (บุคคล) เท่านั้น ห้ามแก้หัวคอลัมน์ในแถวที่ 1"],
    ["", "บุคคลที่มีในทะเบียนแล้ว (เลขประจำตัวประชาชนตรงกัน หรือชื่อและวันเกิดตรงกัน) จะถูกข้าม"],
    ["", "ระบบจะแสดงตัวอย่างและแถวที่ผิดให้ตรวจก่อน ยังไม่บันทึกจนกว่าจะกดยืนยัน"],
    ["", "ไฟล์นี้นำเข้าเฉพาะข้อมูลบุคคล ตำแหน่งปกครองให้บันทึกในหน้าประวัติรายบุคคล"],
  ]);
  help.getRow(1).font = { bold: true };

  return workbookResponse(workbook, "แม่แบบนำเข้าบุคคล.xlsx");
}
